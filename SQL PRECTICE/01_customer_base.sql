-- Business Question:
-- Which years are present in the dataset, and how many transactions occurred in each year?

SELECT EXTRACT(YEAR FROM invoice_date) AS year,
       COUNT(*) AS transactions
FROM online_retail
GROUP BY EXTRACT(YEAR FROM invoice_date);

