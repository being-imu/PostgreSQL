-- Business Question:
-- How much revenue was generated in each month of the year,
-- regardless of which year it was?

SELECT EXTRACT(MONTH FROM invoice_date) AS month,
       SUM(quantity * price) AS total_revenue
FROM online_retail
GROUP BY EXTRACT(MONTH FROM invoice_date)
ORDER BY month ASC;

-- ============================================================

-- Business Question:
-- How did monthly revenue compare with the previous month?

SELECT month,
       total_revenue,
       LAG(total_revenue) OVER (ORDER BY month) AS previous_month_revenue
FROM (
    SELECT EXTRACT(MONTH FROM invoice_date) AS month,
           SUM(quantity * price) AS total_revenue
    FROM online_retail
    GROUP BY EXTRACT(MONTH FROM invoice_date)
) AS monthly_revenue
ORDER BY month ASC;
-- ============================================================
-- Business Question:
-- How much did monthly revenue increase or decrease compared with the previous month?

SELECT month,
       total_revenue,
       previous_month_revenue,
       total_revenue - previous_month_revenue AS revenue_change
FROM (
    SELECT month,
           total_revenue,
           LAG(total_revenue) OVER (ORDER BY month) AS previous_month_revenue
    FROM (
        SELECT EXTRACT(MONTH FROM invoice_date) AS month,
               SUM(quantity * price) AS total_revenue
        FROM online_retail
        GROUP BY EXTRACT(MONTH FROM invoice_date)
    ) AS monthly_revenue
) AS monthly_comparison
ORDER BY month ASC;
-- ============================================================
-- Business Question:
-- What will the revenue be in the following month?

SELECT month,
       total_revenue,
       LEAD(total_revenue) OVER (ORDER BY month) AS next_month_revenue
FROM (
    SELECT EXTRACT(MONTH FROM invoice_date) AS month,
           SUM(quantity * price) AS total_revenue
    FROM online_retail
    GROUP BY EXTRACT(MONTH FROM invoice_date)
) AS monthly_revenue
ORDER BY month ASC;
