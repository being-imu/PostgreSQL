-- Business Question:
-- How can customers be classified into low-, medium-, and high-value segments based on total revenue?

SELECT customer_id,
       total_revenue,
       CASE
           WHEN total_revenue < 1000 THEN 'Low'
           WHEN total_revenue <= 10000 THEN 'Medium'
           ELSE 'High'
       END AS segment
FROM (
    SELECT customer_id,
           SUM(quantity * price) AS total_revenue
    FROM online_retail
    WHERE customer_id IS NOT NULL
    GROUP BY customer_id
) AS customer_revenue;


-- ============================================================

-- Business Question:
-- How many customers are in each revenue segment (Low, Medium, High)?

SELECT segment, COUNT(DISTINCT customer_id) AS number_of_customers,
FROM (
    SELECT customer_id,
           total_revenue,
           CASE
               WHEN total_revenue < 1000 THEN 'Low'
               WHEN total_revenue <= 10000 THEN 'Medium'
               ELSE 'High'
           END AS segment
    FROM (
        SELECT customer_id,
               SUM(quantity * price) AS total_revenue
        FROM online_retail
        WHERE customer_id IS NOT NULL
        GROUP BY customer_id
    ) AS customer_revenue
) AS customer_segments
GROUP BY segment;

-- ============================================================
-- Business Question:
-- What percentage of customers belong to each revenue segment?
-- Solution 1: Using a scalar subquery

SELECT segment,
       COUNT(DISTINCT customer_id) AS number_of_customers,
       (COUNT(DISTINCT customer_id) * 100.0) /
       (
           SELECT COUNT(DISTINCT customer_id)
           FROM online_retail
           WHERE customer_id IS NOT NULL
       ) AS percentage
FROM (
    SELECT customer_id,
           total_revenue,
           CASE
               WHEN total_revenue < 1000 THEN 'Low'
               WHEN total_revenue <= 10000 THEN 'Medium'
               ELSE 'High'
           END AS segment
    FROM (
        SELECT customer_id,
               SUM(quantity * price) AS total_revenue
        FROM online_retail
        WHERE customer_id IS NOT NULL
        GROUP BY customer_id
    ) AS customer_revenue
) AS customer_segments
GROUP BY segment;

-- Business Question:
-- What percentage of customers belong to each revenue segment?
-- Solution 1: Using a scalar subquery

SELECT segment,
       COUNT(DISTINCT customer_id) AS number_of_customers,
       (COUNT(DISTINCT customer_id) * 100.0) /
       (
           SELECT COUNT(DISTINCT customer_id)
           FROM online_retail
           WHERE customer_id IS NOT NULL
       ) AS percentage
FROM (
    SELECT customer_id,
           total_revenue,
           CASE
               WHEN total_revenue < 1000 THEN 'Low'
               WHEN total_revenue <= 10000 THEN 'Medium'
               ELSE 'High'
           END AS segment
    FROM (
        SELECT customer_id,
               SUM(quantity * price) AS total_revenue
        FROM online_retail
        WHERE customer_id IS NOT NULL
        GROUP BY customer_id
    ) AS customer_revenue
) AS customer_segments
GROUP BY segment;

